#!/usr/bin/env node
/**
 * Writes src/buildInfo.ts with the current build id and timestamp so any
 * deployed bundle is identifiable (Settings → Diagnostics, error reports).
 * Runs automatically via the `prebuild` npm script; safe to run standalone.
 */
import { writeFileSync } from 'node:fs';
import { randomBytes } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'buildInfo.ts');
const buildId = randomBytes(4).toString('hex');
const buildTime = new Date().toISOString();
writeFileSync(
  out,
  `// Generated by scripts/gen-build-info.mjs — do not edit by hand.\nexport const BUILD_INFO: { buildId: string; buildTime: string } = { buildId: '${buildId}', buildTime: '${buildTime}' };\n`,
);
console.log(`build info: ${buildId} @ ${buildTime}`);
